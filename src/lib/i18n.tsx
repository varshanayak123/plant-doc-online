const translations = { en, hi, mr };
const Context = createContext<{
  language: Language;
  setLanguage: (l: Language) => void;
  t: (k: Key) => string;
}>({ language: "en", setLanguage: () => {}, t: (k) => en[k] });
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLang] = useState<Language>("en");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("agrovision-language");
      if (saved === "en" || saved === "hi" || saved === "mr") setLang(saved);
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const setLanguage = (l: Language) => {
    setLang(l);
    try {
      localStorage.setItem("agrovision-language", l);
    } catch {}
  };
  return (
    <Context.Provider value={{ language, setLanguage, t: (k) => translations[language][k] }}>
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
